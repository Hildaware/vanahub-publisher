import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const schema = JSON.parse(
  await readFile(join(root, 'vendor/vanahub/package.schema.json'), 'utf8'),
);
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { esm: true, source: true },
});
addFormats(ajv);
const validate = ajv.compile(schema);
const output = join(root, 'src/generated/package-validator.js');
const generated = standaloneCode(ajv, validate)
  .replace('const func2 = require("ajv/dist/runtime/ucs2length").default;', '')
  .replace(
    'const formats0 = require("ajv-formats/dist/formats").fullFormats.uri;',
    'const formats0 = fullFormats.uri;',
  );
await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `// @ts-nocheck\n// Generated by npm run schema:generate from the pinned package schema.\nimport func2 from 'ajv/dist/runtime/ucs2length.js';\nimport { fullFormats } from 'ajv-formats/dist/formats.js';\n${generated}\n`,
);
console.log('generated CSP-compatible package validator');
